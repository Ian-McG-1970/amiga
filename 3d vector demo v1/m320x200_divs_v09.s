SIN_COS:	macro
		LEA		sintab,a4
		LEA		costab,a5

		move.w	ophi,d1
		add.w	d1,d1
		move.w	(a4,d1.w),sphi
		move.w	(a5,d1.w),cphi

	endm

; rotate around y-axis:
;	x'' = x'*cos() + z*sin()
;	z'' = x'*sin() - z*cos()

