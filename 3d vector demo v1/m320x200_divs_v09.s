			moveq.l	#9,d1
			BSR		HEX32
			MOVE.L	YOFFSET,D0
			moveq.l	#18,d1
			BSR		HEX32

			MOVE.L	TEST_Z0,D0
			move.l	#(6*40)+0,d1
			BSR		HEX32
			MOVE.L	TEST_X0,D0
			move.l	#(6*40)+9,d1
			BSR		HEX32
			MOVE.L	TEST_Y0,D0
			move.l	#(6*40)+18,d1
			BSR		HEX32

			MOVE.L	TEST_Z1,D0
