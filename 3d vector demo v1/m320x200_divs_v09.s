ROTATE_Y:	macro

		move.w	d0,d3
		muls.w	cphi,d0 ; x*cos()
		add.l	d0,d0
		swap	d0

		move.w	d2,d4
		muls.w	sphi,d4 ; z*sin()
		add.l	d4,d4
		swap	d4

		add.w	d4,d0 ; x = x*cos() + z*sin()

		muls.w 	sphi,d3	 ; x*sin()
		add.l	d3,d3
		swap	d3

		muls.w	cphi,d2 ; z*cos()
		add.l	d2,d2
		swap	d2

		sub.w	d2,d3
		move.w	d3,d2 ; z = x*sin() - z*cos()

	endm

