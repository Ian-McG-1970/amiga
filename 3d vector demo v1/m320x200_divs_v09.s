		OR.W	d1,d0
		MOVE.W	d0,INTREQ(a1)

		MOVE.W	(A7)+,d0			; restore enabled interrupts
		OR.W	d1,d0
		MOVE.W	d0,INTENA(a1)

		MOVE.W	(A7)+,d0			; restore enabled dma channels
		OR.W	d1,d0
		MOVE.W	d0,DMACON(a1)

